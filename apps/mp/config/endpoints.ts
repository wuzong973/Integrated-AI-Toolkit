/**
 * 后端地址配置 —— **这是全项目唯一需要改地址的地方**（任务清单 M0-19）
 *
 * 为什么不写在 `utils/env.ts` 里：
 * 曾经三个地址与 `const ENV = 'develop'` 混在同一个文件，导致两个问题 ——
 *  ① 切环境要改源码常量，极易漏改，把开发地址随正式版发上线；
 *  ② 改地址要动业务代码文件，review 时容易漏看。
 * 现在本文件只放**地址数据**，`utils/env.ts` 只负责**选择与校验**。
 *
 * ⚠️ 三条硬性要求：
 *  1. **本文件严禁写任何密钥 / AppSecret** —— 小程序包是可被解包反编译的。
 *  2. `develop` 用 `127.0.0.1` 只在**开发者工具**里有效；
 *     真机调试 / 预览二维码时，`127.0.0.1` 指向**手机自己**，必然连不上，
 *     必须改成**局域网 IP**（如 `http://192.168.1.8:3000`）。
 *  3. `trial` / `release` 必须是**已备案 + HTTPS + 已加入小程序后台 request 合法域名**
 *     的真实域名；未配置前保持占位，`utils/env.ts` 会**主动报错**而不是静默连不上。
 */

/**
 * 开发环境基址（开发者工具 + 真机调试 + 预览二维码都用它）。
 *
 * 当前配置：**开发期直连线上服务器**（2026-10-09 起）。开发时看到的就是线上真实数据
 * 与已部署的能力，不必在本地维护一套后端。
 *
 * ⚠️ 三个代价，用之前要清楚：
 *  1. 请求打到**生产库** —— 发需求、下单、增删改都落在真实数据上，别拿它做破坏性试验；
 *  2. 改后端代码不会生效：要热重启或看日志，得自己起本地后端并切回下面的局域网地址；
 *  3. `npm run check:api-base` 在本模式下只探测线上 `/health`，不再比对网卡地址，
 *     也不会把这里改回局域网 IP。
 *
 * **改回本地后端**：值换成本机局域网 IP（`ipconfig` 看「无线局域网适配器 WLAN」下的 IPv4；
 * 家用路由器是 DHCP，**换网络（换个 Wi-Fi / 重启路由器 / 手机热点）这个 IP 就会变**），
 * 再跑 `npm run check:api-base` 确认后端真在这个地址上应答。
 * ⚠️ 不能填 `127.0.0.1` —— 真机上回环地址指向**手机自己**，
 * 表现为「所有请求 `(failed)`、耗时几十毫秒、0 B」，看起来像网络抖动，实际是地址错了。
 * 这类故障 2026-09-20 实测踩过一次：本机从 `192.168.11.x` 换到了 `192.168.31.x`，
 * 配置里还是旧 IP，现象是「所有请求 `ERR_CONNECTION_TIMED_OUT`」，
 * **看起来像后端挂了，其实后端好好的**，后端一直正常监听 0.0.0.0:3000。
 *
 * ⚠️ 直连线上还要求该域名已加入微信公众平台「开发设置 → 服务器域名」的
 * request / uploadFile / downloadFile / socket 四类白名单，否则真机预览会失败，
 * 而**开发者工具勾了"不校验合法域名"时看不出来**。
 */
