/**
 * 对话内 AI 结果卡（服务端产出、小程序渲染）
 *
 * ## 为什么结果不能只是一句文字
 *
 * 助手说"PPT 已经生成好了"，用户下一步要能**真的拿到它**。
 * 只给文字就会出现最糟的形态：话说了、产物也在，但用户不知道该去哪找。
 * 所以每次能力调用都要回一张**结构化卡片**，把「产物在哪、按什么参数做的、
 * 状态是什么」三件事说清楚，并带上可点的作业 id。
 *
 * ## 三种形态（`kind`）—— 必须分开渲染
 *
 * - `result`：**本轮真的执行过了**。带 `jobId`，点卡片进结果页查看/下载，或看进度。
 * - `guide`：**本轮没有执行**，因为缺文件。带 `route`，点卡片进执行页去选文件。
 * - `files`：**本轮没有执行，但用户手上可能已经有产物**（往期生成或上传的）。
 *   带 `route`，点卡片进「我的文件」。
 *
 * ⚠️ 这三种绝不能混：把 `guide` / `files` 渲染成"已完成"，就是红线 9 说的假成功。
 * 小程序的卡片样式也必须能区分（`guide` 虚线 + 警示色；`files` 中性色 + 明确不说"完成"）。
 *
 * ## `files` 是怎么来的（它为什么必须存在）
 *
 * 真机实测：同一会话里第二次提同样需求时，模型会**把历史里自己上一轮的
 * "已经为您生成…"当成既成事实**，于是不再调用工具、直接复述结论 ——
 * 用户看到"点下面的卡片查看"而下面什么都没有。
 *
 * 出口净化（`guardFalseCompletion`）会补一句"本轮没有实际执行"的事实，
 * 但**只补一句话是不够的**：用户真正想要的东西很可能**真的存在**（就在上一轮生成的那次），
 * 只是他没有任何路径去找。所以这里再给一张「我的文件」卡，
 * 把"东西在哪"这件事答完 —— 既不谎报本轮，也不让用户空手。
 *
 * ## 与小程序的一致性
 *
 * 小程序侧在 `apps/mp/utils/os.ts` 里有一份**同名同形**的类型声明
 *（`OsToolCard`），靠注释对齐 —— 小程序**不能** import `@qz/core` 或后端代码
 *（`require('@qz/core')` 在开发者工具里解析不到），这是本项目的既定约束。
 * 改字段必须两边一起改，`npm run audit:mp` 会核对 wxml 绑定的字段是否存在。
 */
export interface OsToolCard {
  kind: 'result' | 'guide' | 'files';
  /** 能力对应的工具名（点卡片时回传给执行页，用于二次校验）；`files` 卡为空串 */
  toolName: string;
  /** 卡片标题，如「AI PPT 生成」「我的文件」 */
  title: string;
  /** 一句话说明（结果卡是产物描述，其余两形是"你需要先做什么/东西在哪"） */
  summary: string;
  /** 参数摘要：把"我按什么参数做的"如实摊开，用户才能判断要不要重做 */
  params: { label: string; value: string }[];
  /** `kind=result` 时的作业 id */
  jobId?: string;
  /** `kind=result` 时的作业状态（如 queued / running / succeeded / failed） */
  status?: string;
  /** `kind=result` 且已完成时的产物数量 */
  outputCount?: number;
  /** `kind=guide` / `kind=files` 时点卡片要跳的小程序路由 */
  route?: string;
  /** 结果不好看时的一句提醒（如失败原因、异步作业的"可去结果页看进度"） */
  note?: string;
}

/** 「我的文件」页（小程序分包页，`app.json` 的 pkg-toolbox 里登记过） */
const FILES_ROUTE = '/pkg-toolbox/files/index';

/**
 * 构建「我的文件」卡（见 `OsToolCard` 里 `files` 形态的说明）。
 *
 * ## 为什么**无条件**建卡（哪怕一个文件都没有）
 *
 * 一开始的做法是"先查数量，0 就不给卡"（理由是"别给一个点进去是空的入口"）。
 * 真机探针推翻了这个判断：长任务（PPT）是异步的，
 * 触发净化时**作业往往还在跑、文件尚未落盘** —— 于是最需要这张卡的那一刻，
 * 它恰好不出现。
 *
 * 想清楚之后其实不矛盾：这张卡的文案已经明说「这一轮没有实际生成文件」，
 * 用户点进去看到空列表与这句话是**一致的**，不算误导；
 * 真正会误导的是"说了完成却不给出路"。所以卡照给，只是**话说清楚**。
 *
 * @param fileCount 该用户当前可见的文件数（服务端查出来的真实值）。
 *   `0` 时换一套不含数量的说法 —— 不能写"你名下 N 个文件"却一个都没有。
 */
export function buildFilesCard(fileCount: number): OsToolCard {
  const has = fileCount > 0;

  return {
    kind: 'files',
    toolName: '',
    title: '我的文件',
    summary: has
      ? `你名下有 ${fileCount} 个文件（此前生成或上传的），可查看、下载或再次使用`
      : '上传或生成过的文件都会出现在这里',
    params: [],
    route: FILES_ROUTE,
    note: has
      ? '上面这一轮没有新生成文件，这里是你已有的文件'
      : '上面这一轮没有实际生成文件；这里是文件列表，目前还没有内容',
  };
}
