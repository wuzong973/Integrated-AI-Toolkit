-- 作业尝试次数（Q6 self-refine 的自评估基础）
--
-- ## 这个字段回答什么问题
--
-- 质检不达标时会带反馈重写一次，然后取两次里分高的那个。这套机制值不值，
-- 需要一个可观测的数字来回答：
--
--   · 触发频率有多高？（`attempts=2` 的作业占比）
--   · 重写真的有效吗？（需要配合 quality_score 与日志里的"重写生效/未改善"）
--   · 成本涨了多少？（触发率 × 2 倍 token）
--
-- 没有这个数字，"自修复"就只能靠感觉评价；有了它，两周一跑的抽样就能给出结论，
-- 也才能决定是否值得推广到更多工具。
--
-- ## 为什么默认 1 而不是 0
--
-- 1 表示"一次过"，是所有不触发重写的作业（含非 AI 工具）的真实含义。
-- 默认 0 会让历史数据与"没尝试过"混淆 —— 而这是红线 10 反对的语义模糊。

ALTER TABLE `tool_job`
  ADD COLUMN `attempts` INT NOT NULL DEFAULT 1 COMMENT '实际尝试次数（1=一次过；2=质检不达标后重写一次）';