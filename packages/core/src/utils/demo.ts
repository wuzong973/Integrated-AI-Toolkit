/**
 * 演示数据识别（红线 10 的服务端落点）。
 *
 * ## 为什么需要它
 *
 * `prisma/seed.ts` 会写入 4 条**示例任务**（"社团招新海报 + 展架设计"等），
 * 它们的 `taskNo` 带 `QZ-DEMO-` 前缀。而小程序的任务大厅**不渲染 `taskNo`**，
 * 于是用户看到的是 4 条看起来完全真实的任务：有发布者昵称、有报名人数、有预算。
 *
 * 这与"假数据冒充功能"是同一类问题（红线 10）：用户无法分辨
 * "这是平台的真实任务" 还是 "这是造出来的示例"。
 *
 * ## 为什么把前缀放在 core 而不是各自硬编码
 *
 * seed 与业务代码必须用**同一个**前缀，否则改名时只改一处 ——
 * 结果就是标记静默失效（`isDemoTaskNo` 永远返回 false），
 * 而界面上的"演示数据"角标再也不出现，且**不会有任何报错**。
 *
 * ## 判据为什么不依赖数据库字段
 *
 * 加一个 `isDemo` 列需要迁移 + 回填，而 seed 数据本身已经带了
 * 可辨识的编号前缀 —— 用编号做判据**不需要改表**，也不会漏掉历史数据。
 * 代价是"业务上真有人把编号起成 QZ-DEMO-xxxx"时会误判，
 * 但编号格式由平台生成（见任务编号生成规则），不存在这种可能。
 */

/** 示例数据的任务编号前缀 */
export const DEMO_TASK_NO_PREFIX = 'QZ-DEMO-';

/** 该任务编号是否属于示例数据（大小写不敏感，容错空值） */
export function isDemoTaskNo(taskNo?: string | null): boolean {
  return (taskNo ?? '').toUpperCase().startsWith(DEMO_TASK_NO_PREFIX);
}
