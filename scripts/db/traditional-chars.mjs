const TRADITIONAL = new Set(TRADITIONAL_CHARS);

/**
 * 这句中文里有没有繁体字。
 *
 * 按**码位**遍历（`for...of`）而不是下标 —— 表里全在 BMP 内，
 * 但用码位遍历可以避免以后加扩展区字时的代理对陷阱。
 */
export function hasTraditional(text) {
  if (typeof text !== 'string' || !text) return false;
  for (const ch of text) if (TRADITIONAL.has(ch)) return true;
  return false;
}

/** 找出文本里的全部繁体字（去重，用于报错时指出是哪几个字） */
export function findTraditional(text) {
  if (typeof text !== 'string' || !text) return [];
  const hit = new Set();
  for (const ch of text) if (TRADITIONAL.has(ch)) hit.add(ch);
  return [...hit];
}

export { TRADITIONAL_CHARS, TRADITIONAL };
