/**
 * 对话回复净化 —— 服务端出口的最后一道防线。
 *
 * ## 为什么需要它
 *
 * 系统提示词里已经写明"不要编造平台功能"，但**提示词拦不住所有模型**。
 * 实测（2026-09-18）：降级链里的 `glm-4-flash` 在回答
 * "帮我把这份 PPT 生成配套路演演讲稿" 时给出了
 * `https://www.qingzhi.com/ai/ppt` —— 平台里根本没有这个地址。
 *
 * 降级链**必须**保留 `glm-4-flash`（主模型 429 过载时，"快但可能编造"
 * 好过"等 60 秒还可能失败"），所以这个风险无法靠换模型消除，
 * 只能在出口再拦一道。
 *
 * ## 为什么可以"直接删掉链接"而不是改写
 *
 * 青智校园是**微信小程序**，没有任何面向用户的网页地址；
 * 工具入口由客户端按 intent 渲染成按钮（见 `apps/mp/pages/os/index.ts`
 * 的 `renderReply` + `INTENT_TOOL_MAP`）。
 * 所以回复正文里出现 URL **没有任何正当用途** —— 删掉不会损失信息。
 *
 * 净化后若正文被清空，客户端会用 `intentFallbackText(intent)` 兜底
 * （按意图给一句诚实的话），服务端不重复维护第二套兜底文案。
 */

/** Markdown 图片：整段删掉（图片比链接更没必要出现在对话里） */
const MD_IMAGE = /!\[[^\]]*\]\(\s*[^)\s]*\s*\)/g;

/** Markdown 链接：`[文字](url)` → 只留「文字」 */
const MD_LINK = /\[([^\]]*)\]\(\s*[^)\s]*\s*\)/g;

/**
 * 裸 URL。
 *
 * 字符类里显式排除中文标点 —— 否则 `https://x.com/a，然后` 会把「，然后」也吃进去。
 * 这是实测踩过的：`[^\s]+` 在中文句子里会一直吞到行尾。
 */
const BARE_URL = /(?:https?:\/\/|www\.)[^\s，。；：！？、（）"'【】「」《》]+/gi;

/**
 * 删链接后残留的空括号。
 *
 * 用「配对写全」而不是字符类 `[（(【[]\s*[）)】\]]` ——
 * 后者里的 `[` / `]` 在字符类中容易读错，且 `\[` 会被 lint 判为多余转义。
 */
const EMPTY_BRACKETS = /（\s*）|\(\s*\)|【\s*】|\[\s*\]/g;

/** 是否有"实际内容"（中英文、数字任一） */
const HAS_CONTENT = /[\u4e00-\u9fa5a-zA-Z0-9]/;

/**
 * 推理标签残留。
 *
 * ## 为什么会出现
 *
 * 推理型模型（智谱 GLM / 硅基的 DeepSeek-V4-Flash）把"思考过程"放在
 * `reasoning_content` 里，结论放在 `content`。多数情况下两者是分开的，
 * 但实测**带了 `reasoning_effort` 参数时**，个别服务商会把闭合标签漏进 `content`：
 *
 * ```
 * 只回复两个字：可以  →  "可以</think>可以"
 * ```
 *
 * 也就是说：正常内容被标签**切断并重复**了一次。同一请求去掉该参数则输出干净。
 *
 * ## 为什么在出口删而不是在 Provider 里清洗
 *
 * Provider 只该负责"协议与容错"，不该猜哪段文本是元数据。
 * 而且这类残留可能来自任何一层（模型 / 网关 / 将来换的服务商），
 * 出口是唯一能覆盖全部来源的位置。删标签是**幂等且零信息损失**的：
 * `</think>` 本身不是给用户看的内容。
 */
const THINK_TAG = /<\/?think>/gi;

/** 完整包裹的推理块：`...` 整段删掉（连同里面的思考过程） */
const THINK_BLOCK = /<think>[\s\S]*?<\/think>/gi;

/**
 * 净化模型回复：去掉一切 URL 痕迹与推理标签残留。
 *
 * 幂等 —— 对已净化的文本再跑一次结果不变。
 */
export function sanitizeAssistantReply(raw: string): string {
  let out = (raw ?? '')
    // 整块推理必须在裸标签之前处理：否则先删掉 `<think>` 就再也匹配不到成对结构了
    .replace(THINK_BLOCK, '')
    .replace(THINK_TAG, '')
    .replace(MD_IMAGE, '')
    .replace(MD_LINK, '$1')
    .replace(BARE_URL, '');

  out = out
    .replace(EMPTY_BRACKETS, '')
    // 删链接留下的双空格 / 行尾空格
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/[ \t]+$/gm, '')
    // 删链接留下的重复标点（如「，，」「。。」）
    .replace(/([，。；：！？、])\1+/g, '$1')
    .trim();

  // 只剩标点（如模型整段就输出一个链接）→ 视为空，交给客户端兜底
  return HAS_CONTENT.test(out) ? out : '';
}

/**
 * 声称"已完成"的说法。
 *
 * 允许中间夹一层「为您 / 为你」——实测模型最爱的说法正是
 * 「已经**为您**生成了一份…」，中间插了宾语，简单写 `已经生成` 会漏掉，
 * 而这个说法恰好是最需要拦的那一个。
 */
const DONE_CLAIM =
  /已(?:经)?\s*(?:为(?:您|你))?\s*(?:生成|完成|做好|提交|处理完|创建|开始处理)|正在(?:为(?:您|你))?(?:生成|处理|后台处理)|已生成|已提交|已处理完/;

/**
 * 是否属于"假成功"：**声称做完了，但这一轮其实什么都没执行**。
 *
 * 单独导出（而不是只在 `guardFalseCompletion` 内部用）是因为**调用方还要据此做第二件事**：
 * 补一张「我的文件」卡 —— 用户想要的东西很可能真的存在于上一轮，
 * 只补一句"我没执行"等于只告诉他坏消息、却不给出路。
 * 见 `os-tool-card.ts` 里 `files` 形态的说明。
 *
 * @param executed 这一轮是否真的执行过工具（由 `chatWithTools` 统计，不依赖文案）
 */
export function isFalseCompletion(reply: string, executed: boolean): boolean {
  return !executed && DONE_CLAIM.test(reply ?? '');
}

/**
 * 假成功净化：**声称做完了，但这一轮其实什么都没执行**。
 *
 * ## 为什么必须拦
 *
 * 这是实测出来的、比编造链接更严重的一类失败：
 *
 * ```
 * 用户：帮我做一份校园二手交易平台的 PPT，课程汇报用，12 页
 * 助手：已经为您生成了一份…PPT，共 12 页。点下面的卡片查看详情。   ← 而下面没有卡片
 * ```
 *
 * 模型为什么这么说：**上下文历史里有它自己上一轮说过的"已经为您生成…"**，
 * 它把历史当成了"这件事已经做过了"，于是不再调用工具、直接复述结论。
 * 用户看到"点卡片查看"却找不到任何卡片 —— 比干脆失败更糟。
 *
 * ## 为什么只加一句说明，而不是改写或删掉回复
 *
 * 替换整段回复需要判断"哪句是假话"，那本身又是一次不可靠的猜测；
 * 而**"本轮没有执行任何动作"是服务端确知的事实**（它自己刚跑完工具循环）。
 * 把确知的事实补上去，既不会误伤（说的都是真的），又足以消除误导。
 *
 * 注意这里**不假装成功、也不替模型道歉**：它只陈述事实并给出下一步。
 * 而"下一步"里"已有的文件去哪找"由 `os.service.ts` 附上的「我的文件」卡负责 ——
 * 文案与卡片缺一不可：只补一句"我没执行"会让用户以为东西没了。
 */
export function guardFalseCompletion(reply: string, executed: boolean): string {
  const text = reply ?? '';
  if (!isFalseCompletion(text, executed)) return text;

  return (
    `${text}\n\n` +
    '（说明：这一轮我没有实际执行任何动作，所以下面没有新的结果卡。' +
    '如果你希望我现在就做这件事，再发一次需求即可，我会立刻开始。）'
  );
}
